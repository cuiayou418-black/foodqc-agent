"""
judge_tool.py —— 判定工具（W3 Day15）

职责：把「实测值 vs 限值，谁大谁小」这件事从模型手里收回代码。
      模型只负责报数，判定结论必须由这里给出 —— 这是四条原则第一条的落点。

⚠️ 当前是【第一版，有方向性缺陷】。Day15 的任务就是修好它。
   已知缺陷：一律按「实测 > 限值 = 不达标」处理，只适用于上限型（≤）；
             遇到下限型（≥）会判反 —— 见 test_judge.py 的失败用例。
"""

import re


def judge(value: float, limit_expr: str) -> str:
    """判定实测值是否达标。

    参数
    ----
    value:      实测值，如 76.5
    limit_expr: 限值原文，如 "≥77.0"（下限型）或 "≤1.0"（上限型）

    返回
    ----
    "合格（实测X vs 限值Y）" 或 "不达标（实测X vs 限值Y）"

    术语说明
    --------
    统一叫「不达标」而不是「超标」：因为出糙率不够只能叫不达标/降等，
    叫「超标」本身就暴露了「只想到上限型」的思维盲区。
    """
    m = re.search(r"[\d.]+", limit_expr)
    if not m:
        return f"无法判定：限值里没找到数字（{limit_expr}）"
    lim = float(m.group())

    # ════════════════════════════════════════════════════════════
    # ⬇️ 这里是 bug —— 它不管 ≥ 还是 ≤，一律按上限型判。
    #
    # 你要做的（读完再改，别急着下手）：
    #   1. 先从 limit_expr 里读出方向。注意 PDF 抽出来的符号可能不规整：
    #      "≥" / ">=" / "≥" 都可能出现，先打印看看你手里到底是什么
    #   2. 下限型（≥）：实测 < 限值 才不达标；实测 == 限值 算达标
    #   3. 上限型（≤）：实测 > 限值 才不达标；实测 == 限值 算达标
    #   4. 读不出方向时：别硬猜，返回"无法判定"让人工接手（安全侧默认）
    #
    # 改完跑：python test_judge.py     6 条必须全绿
    # ════════════════════════════════════════════════════════════
    if "≥" in limit_expr:        #下限型
        ok = value >= lim
    elif "≤" in limit_expr:      #上限型
        ok = value <= lim
    else:
        return f"无法判定：限值里没有 ≥ 或 ≤（{limit_expr}）"

    return f"{'合格' if ok else '不达标'}（实测{value} vs 限值{limit_expr}）"

if __name__ == "__main__":
    # 手跑几条看看当前行为
    for v, e in [(76.5, "≥77.0"), (1.5, "≤1.0")]:
        print(judge(v, e))
